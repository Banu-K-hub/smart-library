"""Мәтінді өңдеу утилиталары / Утилиты обработки текста.

Қазақ және орыс тілдеріндегі мәтінді іздеуге дайындайды.
"""
import re

# Сұрауда жиі кездесетін, бірақ мағына бермейтін сөздер (stop-words)
STOP_WORDS = {
    # kk
    "маған", "керек", "кітап", "кітабы", "кітаптар", "кітаптары", "туралы", "бар", "ма", "ме", "ба", "бе",
    "қандай", "бір", "және", "мен", "пен", "бен", "осы", "сол", "не", "ұсыныңыз", "ұсын", "ұсынып",
    "беріңізші", "беріңіз", "іздеймін", "оқығым", "келеді", "жақсы", "қызық", "кітапты", "жайлы",
    # ru
    "мне", "нужна", "нужен", "нужно", "книга", "книгу", "книги", "про", "о", "об", "есть", "ли", "какую",
    "какой", "какие", "и", "в", "на", "что", "посоветуй", "посоветуйте", "хочу", "почитать", "хорошую",
    "интересную", "что-нибудь", "найди", "найти", "по", "для",
}

_KZ_MAP = str.maketrans({"ё": "е"})


def normalize(text: str) -> str:
    """Кіші әріпке келтіру, тыныс белгілерін алып тастау."""
    text = (text or "").lower().translate(_KZ_MAP)
    text = re.sub(r"[«»\"'(),.!?:;…—–\-]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def content_words(text: str) -> list[str]:
    """Stop-сөздерсіз мағыналы сөздер тізімі."""
    return [w for w in normalize(text).split() if w not in STOP_WORDS and len(w) > 1]


def detect_lang(text: str) -> str:
    """Қазақ әрпі болса — 'kk', әйтпесе 'ru'. Қарапайым эвристика."""
    if re.search(r"[әғқңөұүһі]", (text or "").lower()):
        return "kk"
    kk_markers = {"ма", "ме", "бар", "туралы", "кітап", "маған", "керек", "қалай"}
    words = set(normalize(text).split())
    return "kk" if words & kk_markers else "ru"
